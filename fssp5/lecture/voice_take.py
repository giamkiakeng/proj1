#!/usr/bin/env python3
"""voice_take.py -- the narration as a beat-numbered script for a narrator, and the bookkeeping that lets
build.py lay the finished take under the slides.

usage: voice_take.py OUTDIR [--narrator DIR]

Writes
  OUTDIR/script.md             one beat per slide, "`N` text" (N = 1, 2, ... in slide order); the
                               paragraphs of a beat are joined by **(beat)**, a pause
  OUTDIR/voice/direction.json  longer pauses after a chapter title and before the next chapter
  OUTDIR/sentences.json        every sentence: its beat, its caption text, and the text that is read
The narrator reads OUTDIR/script.md into OUTDIR/voice/recording.wav with OUTDIR/voice/recording.cues.json
(the start and end of every chunk it read, and its beat); then build.py --take OUTDIR/voice/recording.wav.

With --narrator, the narrator's own reading rules (narrate_script.to_speech: numbers as words and so on)
are applied to each sentence for sentences.json, so build.py can match its sentences to the chunks exactly.
"""
import argparse
import json
import os
import sys

import lecture_lib as L

CHAPTER_GAP = 1.8        # seconds after a chapter title
END_OF_CHAPTER_GAP = 1.4  # seconds after the last beat of a chapter


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('outdir')
    ap.add_argument('--narrator', help='directory with narrate_script.py, for its reading rules')
    a = ap.parse_args()
    to_speech = None
    if a.narrator:
        sys.path.insert(0, os.path.abspath(a.narrator))
        from narrate_script import to_speech
    chapters, beats = L.parse_script()
    os.makedirs(os.path.join(a.outdir, 'voice'), exist_ok=True)
    lines = ['# Two barriers for minimal-time firing squads: the lecture', '',
             '> Generated by voice_take.py from script*.txt: one beat per slide.', '']
    sents, direction = [], {'finish': {'style': 'real'}, 'heard': L.NARRATOR_HEARD, 'beats': {}}
    for n, b in enumerate(beats, 1):
        pars = []
        for par in b['paragraphs']:
            read = [L.spoken_form(s['raw'], L.NARRATOR_SPOKEN) for s in par]
            pars.append(' '.join(read))
            for s, r in zip(par, read):
                sents.append({'beat': n, 'id': b['id'], 'display': s['display'], 'spoken': r,
                              'read': to_speech(r, {}, 1.0) if to_speech else r})
        lines += ['`%d` %s' % (n, ' **(beat)** '.join(pars)), '']
        if b['id'].startswith('ch'):
            direction['beats'][str(n)] = {'gaps': {'beat': CHAPTER_GAP}}
        elif n < len(beats) and beats[n]['id'].startswith('ch'):
            direction['beats'][str(n)] = {'gaps': {'beat': END_OF_CHAPTER_GAP}}
    open(os.path.join(a.outdir, 'script.md'), 'w', encoding='utf-8').write('\n'.join(lines))
    with open(os.path.join(a.outdir, 'voice', 'direction.json'), 'w', encoding='utf-8') as fh:
        json.dump(direction, fh, indent=1, ensure_ascii=False)
    with open(os.path.join(a.outdir, 'sentences.json'), 'w', encoding='utf-8') as fh:
        json.dump({'beats': [b['id'] for b in beats], 'sentences': sents}, fh, indent=1, ensure_ascii=False)
    print('%d beats, %d sentences, %d words' % (len(beats), len(sents), sum(len(s['read'].split()) for s in sents)))


if __name__ == '__main__':
    main()
